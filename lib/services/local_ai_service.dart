  // --- 核心功能：隨機產生一句話 ---
  static String getRandomComment(String categoryName, {String? petKey}) {
    // 1. 從目前存在的 16 隻動物隨機挑一隻 (斷網時的備用邏輯)
    final random = Random();
    // ★★★ 修改：優先使用「當前上場的寵物」；沒傳或查無此寵物時，才退回隨機盲抽 ★★★
    final String animal = (petKey != null && _quotes.containsKey(petKey))
        ? petKey
        : _animals[random.nextInt(_animals.length)];

    // 2. 智慧分類判斷 (Keyword Matching)
    // 將所有分類關鍵字正規化，對應到我們的語錄 key
    String type = 'default';
    String cat = categoryName;

    // --- 飲食類 ---
    if (cat.contains('食') || cat.contains('餐') || cat.contains('飲') || cat.contains('吃') || cat.contains('喝') || cat.contains('外送')) {
      type = 'food';
    }
    // --- 購物/服飾/日用 ---
    else if (cat.contains('衣') || cat.contains('飾') || cat.contains('購') || cat.contains('日用') || cat.contains('洗') || cat.contains('貨') || cat.contains('品')) {
      type = 'shopping';
    }
    // --- 交通/行 ---
    else if (cat.contains('行') || cat.contains('交通') || cat.contains('車') || cat.contains('油') || cat.contains('運') || cat.contains('路')) {
      type = 'transport';
    }
    // --- 娛樂/社交 ---
    else if (cat.contains('樂') || cat.contains('玩') || cat.contains('旅') || cat.contains('影') || cat.contains('遊') || cat.contains('訂閱') || cat.contains('社') || cat.contains('聚')) {
      type = 'entertainment';
    }
    // --- 教育/學業 ---
    else if (cat.contains('學') || cat.contains('書') || cat.contains('教') || cat.contains('課') || cat.contains('文具') || cat.contains('印')) {
      type = 'education';
    }
    // --- 醫療/健康 ---
    else if (cat.contains('醫') || cat.contains('藥') || cat.contains('健') || cat.contains('診') || cat.contains('身')) {
      type = 'health';
    }
    // --- 居家/房產 ---
    else if (cat.contains('住') || cat.contains('房') || cat.contains('家') || cat.contains('水') || cat.contains('電') || cat.contains('瓦') || cat.contains('網')) {
      type = 'home';
    }
    // --- 投資/理財/保險 ---
    else if (cat.contains('資') || cat.contains('財') || cat.contains('股') || cat.contains('金') || cat.contains('險') || cat.contains('稅') || cat.contains('貸')) {
      type = 'invest';
    }

    // 3. 從資料庫撈句子 (如果上面都沒對中，就會用 'default')
    final animalQuotes = _quotes[animal] ?? _quotes['dog']!;
    final list = animalQuotes[type] ?? animalQuotes['default']!;

    // 4. 隨機回傳一句
    return list[random.nextInt(list.length)];
  }
